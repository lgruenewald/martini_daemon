# analysis helper for problems where a group of atoms can be permanently mapped
# into a "monomer" unit, and a graph of monomers

import sys
import numpy as np


def generate_mapping(initial_molecules: list[tuple[str, int, int]]):
    """
        From a list of each type of monomer and their number and number of
        atoms, generate a np array that maps each atom to their monomer index.

        Returns the number of monomers, number of atoms and the mapping, all
        based on the initial_molecules list.
    """
    total_monomers = sum([x for _, x, _ in initial_molecules])
    total_atoms = sum([x * y for _, x, y in initial_molecules])
    mapping = np.empty(total_atoms, np.uint32)
    atom = 0
    monomer = 0
    for _, monomer_count, atom_count in initial_molecules:
        for _ in range(monomer_count):
            mapping[atom:atom+atom_count] = monomer
            atom += atom_count
            monomer += 1
    return total_monomers, total_atoms, mapping


def read_monomer_graph(bond_frames: list[np.array], mapping: np.array):
    """
        bond_frames has to be a file read by BondReporter.read_bonds.
        mapping is a mapping generated by generate_mapping from this module.

        Returns: frames - a list of frames, each frame a numpy array
        of dimension (n_bonds, 2), but in this case it is between
        monomers, not between atoms and mapping - a list of what monomer
        each atom belongs to.

        The conversion can take a while, and since the primary
        function of this is to be used in run.py style "recipes"
        this prints progress information to stdout by default.

        The result graph can have multiple connections between monomers,
        if there are multiple bonds between the monomers. Bonds, constraints
        and virtual sites are considered bonds, based on how BondReporter
        reports it. In case of vsites, the virtual particle is considered
        bonded to all constructing particles.
    """
    # input data and uninitialized result
    # make a mapping atom -> monomer
    monomer_frames = []
    for frame in bond_frames:
        # bonds that are between different monomers
        cross_bonds = filter(
            lambda pair: pair[0] != pair[1],
            map(
                lambda pair: (mapping[pair[0]], mapping[pair[1]]),
                frame
            )
        )
        # create a np array for them
        monomer_frames.append(np.fromiter(
            cross_bonds,
            dtype=np.dtype((np.uint32, 2))
        ))
    return monomer_frames


def conversion(
    monomer_frames: list[np.array], start: int, end: int,
    bonds_per_monomer: int
):
    """
        Calculate the degree of conversion in a polymerization reaction.
        - monomer_frames is given by read_monomer_graph
        - Should be calculated for a specific monomer. Its index in the monomer
        list should be between start and end (start inclusive, end not).
        - 100% conversion is reached when all monomers between start and end
        have bonds_per_monomer bonds to other monomers (the other monomers
        can be, but don't have to be between start and end)
    """

    count = end - start
    max_bonds = bonds_per_monomer * count
    conversions = np.empty(len(monomer_frames), np.float32)
    for i, frame in enumerate(monomer_frames):
        conversion = sum(
            map(
                lambda bond:
                    (1 if bond[0] >= start and bond[0] < end else 0) +
                    (1 if bond[1] >= start and bond[1] < end else 0),
                frame
            )
        ) / max_bonds
        if i % 8 == 0:
            print(
                f"Calculating conversion for frame {i}. "
                f"Current conversion {conversion}"
            )
        conversions[i] = conversion
    return conversions


