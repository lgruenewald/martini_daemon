def _unroll(max: int, edge_array: np.array):
    """
        Converts a condensed (np.array of dimension (n_edges, 2)) list of
        edges representation of a graph of 0:max numbers as nodes to a python
        list of sets representation. Information on the multiplicity of bonds
        is lost.
    """
    graph = [set() for _ in range(max)]
    for edge in edge_array:
        graph[edge[0]].add(edge[1])
        graph[edge[1]].add(edge[0])
    return graph


def _find_cycles(graph, max_loop, path):
    """
        Returns a set[set[int]] of loops found starting at path.

        Recursive, slow, naive solution.

        Uses python's built in set semantics to deduplicate.
    """
    res = set()
    if len(path) > max_loop:
        # for performance reasons...
        return res
    neighbors: set[int] = graph[path[-1]]
    for neigh in neighbors:
        if len(path) >= 3 and neigh == path[0]:
            res.add(frozenset(path))
        elif neigh not in path:
            res |= _find_cycles(graph, max_loop, [*path, neigh])
    return res


def loop_analysis(n_monomers, monomer_frames, max_loop=10, progress=False):
    """
        Finds loops between monomers in each frame, up to max_loop in length.

        Does not consider how many bonds there are between a pair of monomers.

        Uses python's set semantics to deduplicate and the recursive and naive
        _find_cycles helper.

        Minimum loop size: 3, maximum loop size: max_loop.

        Can take a while, if progress=True, print updates to stdout to make
        the wait better.
    """
    # set of sets of ints, for each frame
    loops: list[set[frozenset[int]]] = [set() for _ in monomer_frames]

    # naive, slow solution: check for loops starting at each atom, use sets to
    # deduplicate
    for frame_index, frame in enumerate(monomer_frames):
        if progress and frame_index % 16 == 0:
            sys.stdout.write(f"\033[2K\rfinding loops frame {frame_index} of {len(monomer_frames)}")
        loop_set: set[frozenset[int]] = loops[frame_index]
        graph = _unroll(n_monomers, frame)
        for i in range(n_monomers):
            loop_set |= _find_cycles(graph, max_loop, [i])

    if progress:
        sys.stdout.write("\033[2K\r")
    return loops


def find_double_bonds(n_monomers, monomer_frames):
    """
        Finds pairs of monomers connected by exactly 2 bonds. Can be useful
        together with loop analysis to e.g. find 2 large loops, in cases
        where there is one bond normally connecting two monomers, but
        multifunctional monomers can be bonded to eachother twice at
        different ends.
    """
    doubles = [set() for _ in monomer_frames]

    for frame_index, frame in enumerate(monomer_frames):
        graph = [{} for _ in range(n_monomers)]
        for edge in frame:
            l = graph[edge[0]]
            r = graph[edge[1]]

            if l.get(edge[1]) is None:
                l[edge[1]] = 1
            else:
                l[edge[1]] += 1

            if r.get(edge[0]) is None:
                r[edge[0]] = 1
            else:
                r[edge[0]] += 1

        for li, l in enumerate(graph):
            for ri, order in l.items():
                if order == 2:
                    doubles[frame_index].add((li, ri) if li > ri else (ri, li))
    return doubles

